package main

import (
	"io"
	"log"
	"net/http/httptest"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/google/go-containerregistry/pkg/authn"
	"github.com/google/go-containerregistry/pkg/registry"

	"github.com/trianalab/pacto/v4/internal/app"
	"github.com/trianalab/pacto/v4/internal/ci"
	"github.com/trianalab/pacto/v4/pkg/oci"
)

const ciPlanGolden = "generated/ci-plan.md"

// TestCIPlanIsCurrent: the summary docs show for pacto ci is what pacto ci
// plans today on the ci-plan fixture, against baselines pushed to a local
// registry. PACTO_UPDATE_CI_PLAN=1 rewrites it.
func TestCIPlanIsCurrent(t *testing.T) {
	srv := httptest.NewServer(registry.New(registry.Logger(log.New(io.Discard, "", 0))))
	t.Cleanup(srv.Close)
	host := strings.TrimPrefix(srv.URL, "http://")
	t.Setenv("PACTO_INSECURE_REGISTRIES", host)
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	svc := app.NewService(oci.NewClient(authn.NewMultiKeychain(), oci.WithInsecureRegistries(host)), nil)
	for ref, dir := range map[string]string{
		"oci://" + host + "/acme/payments:1.4.2": "ci-plan-baseline/payments",
		"oci://" + host + "/acme/reports:1.0.0":  "ci-plan/services/reports",
		"oci://" + host + "/acme/ledger:1.0.0":   "ci-plan-baseline/ledger",
	} {
		if _, err := svc.Push(t.Context(), app.PushOptions{Ref: ref, Path: dir}); err != nil {
			t.Fatal(err)
		}
	}
	root := filepath.Join(t.TempDir(), "ci-plan")
	if err := os.CopyFS(root, os.DirFS("ci-plan")); err != nil {
		t.Fatal(err)
	}
	p, _, err := svc.CIPlan(t.Context(), app.CIOptions{Root: root, Registry: host + "/acme", Getenv: func(string) string { return "" }})
	if err != nil {
		t.Fatal(err)
	}
	if p.Platform != "" || p.Base.Value != "" || p.Exit != 2 || len(p.Skipped) != 1 || p.Skipped[0].Rule != ".pactoignore:1" {
		t.Fatalf("plan = platform %q, base %+v, exit %d, skipped %+v", p.Platform, p.Base, p.Exit, p.Skipped)
	}
	got := "<!-- Generated by TestCIPlanIsCurrent (PACTO_UPDATE_CI_PLAN=1). Do not edit. -->\n\n" +
		strings.ReplaceAll(strings.ReplaceAll(ci.Markdown(p), host, "ghcr.io"), root, "ci-plan")
	if os.Getenv("PACTO_UPDATE_CI_PLAN") == "1" {
		if err := os.WriteFile(ciPlanGolden, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(ciPlanGolden)
	if err != nil {
		t.Fatal(err)
	}
	if got != string(want) {
		t.Fatalf("%s is stale; run PACTO_UPDATE_CI_PLAN=1 go test ./examples/demo -run TestCIPlanIsCurrent. pacto ci plans:\n%s", ciPlanGolden, got)
	}
}
