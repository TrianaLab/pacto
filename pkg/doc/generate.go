// writeConfigList renders each configuration scope: a remote reference, a
// resolved values table, or a "no properties" note. Multi-scope configs are
// labelled by name. Shared by the root section and the per-dependency detail.
func writeConfigList(b *strings.Builder, configs []dashboard.ConfigurationInfo) {
	multi := len(configs) > 1
	for _, cfg := range configs {
		if multi {
			name := cfg.Name
			if name == "" {
				name = "default"
			}
			fmt.Fprintf(b, "_%s_\n\n", name)
		}
		if cfg.Ref != "" {
			fmt.Fprintf(b, "References: `%s`\n\n", escapeMarkdownCell(cfg.Ref))
			continue
		}
		if len(cfg.Values) == 0 {
			fmt.Fprintln(b, "_No configurable properties._")
			fmt.Fprintln(b)
			continue
		}
		fmt.Fprintln(b, "| Property | Type | Value |")
		fmt.Fprintln(b, "|----------|------|-------|")
		for _, p := range cfg.Values {
			fmt.Fprintf(b, "| `%s` | `%s` | `%s` |\n", escapeMarkdownCell(p.Key), escapeMarkdownCell(p.Type), escapeMarkdownCell(p.Value))
		}
		fmt.Fprintln(b)
	}
}

