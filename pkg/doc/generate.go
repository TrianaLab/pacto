// ── §6 Dependencies ────────────────────────────────────────────────────

func writeDependencies(b *strings.Builder, d *dashboard.ServiceDetails, gr *graph.Result, num *sectionNumberer) {
	if len(d.Dependencies) == 0 {
		return
	}
	fmt.Fprintf(b, "## %s. Dependencies\n\n", num.Next(1))
	writeDependencyTable(b, d.Dependencies)
	for _, node := range collectFlatDependencyNodes(gr) {
		writeDependencyDetail(b, node)
	}
}

func writeDependencyTable(b *strings.Builder, deps []dashboard.DependencyInfo) {
	fmt.Fprintln(b, "| Name | Reference | Compatibility | Required | Locked version | Locked digest | Drift |")
	fmt.Fprintln(b, "|------|-----------|---------------|----------|----------------|---------------|-------|")
	for _, dep := range deps {
		req := "No"
		if dep.Required {
			req = "Yes"
		}
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s | %s | %s |\n",
			escapeMarkdownCell(dep.Name), escapeMarkdownCell(dep.Ref), dash(dep.Compatibility),
			req, dash(dep.LockedVersion), dash(dep.LockedDigest), dash(dep.DriftStatus))
	}
	fmt.Fprintln(b)
}

// collectFlatDependencyNodes returns all unique resolved dependency nodes
// in DFS-discovery order, flattened (no nesting).
func collectFlatDependencyNodes(gr *graph.Result) []*graph.Node {
	if gr == nil || gr.Root == nil {
		return nil
	}
	var nodes []*graph.Node
	seen := map[string]bool{}
	var walk func(edges []graph.Edge)
	walk = func(edges []graph.Edge) {
		for _, edge := range edges {
			if edge.Node == nil || edge.Node.Contract == nil || seen[edge.Node.Name] {
				continue
			}
			seen[edge.Node.Name] = true
			nodes = append(nodes, edge.Node)
			walk(edge.Node.Dependencies)
		}
	}
	walk(gr.Root.Dependencies)
	return nodes
}

// writeDependencyDetail renders a collapsible per-dependency snapshot built from
// the resolved graph node via the same ServiceDetails mapping the dashboard
// uses, so the detail matches the dashboard's view of that dependency.
func writeDependencyDetail(b *strings.Builder, node *graph.Node) {
	nd := dashboard.ServiceDetailsFromBundle(&contract.Bundle{Contract: node.Contract, FS: node.FS}, "local")
	fmt.Fprintf(b, "<details>\n<summary><strong>%s</strong> <code>v%s</code></summary>\n\n", nd.Name, nd.Version)
	if nd.Runtime != nil {
		fmt.Fprintln(b, "**Runtime**")
		fmt.Fprintln(b)
		writeRuntimeTable(b, nd)
	}
	if len(nd.Interfaces) > 0 {
		fmt.Fprintln(b, "**Interfaces**")
		fmt.Fprintln(b)
		writeInterfaceTable(b, nd.Interfaces)
	}
	if len(nd.Configurations) > 0 {
		fmt.Fprintln(b, "**Configuration**")
		fmt.Fprintln(b)
		writeConfigList(b, nd.Configurations)
	}
	if len(nd.Dependencies) > 0 {
		fmt.Fprintln(b, "**Dependencies**")
		fmt.Fprintln(b)
		writeDependencyTable(b, nd.Dependencies)
	}
	fmt.Fprintln(b, "</details>")
	fmt.Fprintln(b)
}

// ── §7 Readiness ───────────────────────────────────────────────────────

func writeReadiness(b *strings.Builder, d *dashboard.ServiceDetails, num *sectionNumberer) {
	if d.Readiness == nil {
		return
	}
	r := d.Readiness
	fmt.Fprintf(b, "## %s. Readiness\n\n", num.Next(1))
	fmt.Fprintf(b, "Score `%d/100` · gate `%d`", r.Score, r.MinScore)
	if r.Expires != "" {
		fmt.Fprintf(b, " · expires `%s`", escapeMarkdownCell(r.Expires))
	}
	fmt.Fprintln(b)
	fmt.Fprintln(b)

	if len(r.Checks) > 0 {
		fmt.Fprintln(b, "| ID | Type | Category | Status | Evidence | Weight | Description |")
		fmt.Fprintln(b, "|----|------|----------|--------|----------|-------:|-------------|")
		for _, ch := range r.Checks {
			fmt.Fprintf(b, "| `%s` | `%s` | %s | `%s` | %s | %d | %s |\n",
				escapeMarkdownCell(ch.ID), escapeMarkdownCell(ch.Type), dash(ch.Category),
				escapeMarkdownCell(ch.Status), dash(ch.Evidence), ch.Weight, dashText(ch.Description))
		}
		fmt.Fprintln(b)
	}

	if len(r.Revisions) > 0 {
		fmt.Fprintln(b, "**Revision History**")
		fmt.Fprintln(b)
		fmt.Fprintln(b, "| Date | Version | Author | Description |")
		fmt.Fprintln(b, "|------|---------|--------|-------------|")
		for _, rev := range r.Revisions {
			fmt.Fprintf(b, "| `%s` | `%s` | %s | %s |\n",
				escapeMarkdownCell(rev.Date), escapeMarkdownCell(rev.Version),
				escapeMarkdownCell(rev.Author), dashText(rev.Description))
		}
		fmt.Fprintln(b)
	}
}

